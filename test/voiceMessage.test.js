import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  isConversationVoiceMessage,
  isVoiceStructured,
  isAudioMeta,
  normalizeWaveform,
  voiceMetaFromMessage,
} from '../src/utils/voiceMessage.js';
import { preferConfirmedThreadText } from '../src/utils/groupPayload.js';

test('isAudioMeta accurately distinguishes audio/voice files from generic attachments', () => {
  assert.equal(isAudioMeta('audio/webm', 'voice-note-123.webm'), true);
  assert.equal(isAudioMeta('audio/mp4', 'audio.m4a'), true);
  assert.equal(isAudioMeta('audio/ogg', 'voice-note.ogg'), true);
  assert.equal(isAudioMeta('', 'voice-note-999.webm'), true);
  assert.equal(isAudioMeta('application/octet-stream', 'voice-note-888.webm'), true);

  // Non-audio attachments
  assert.equal(isAudioMeta('image/png', 'photo.png'), false);
  assert.equal(isAudioMeta('application/pdf', 'document.pdf'), false);
  assert.equal(isAudioMeta('video/mp4', 'video.mp4'), false);
});

test('isConversationVoiceMessage detects voice in DM messages', () => {
  const dmVoice = {
    id: 'dm-msg-1',
    from: 'user-1',
    to: 'user-2',
    text: '',
    attachment: {
      id: 'att-1',
      mimetype: 'audio/webm',
      filename: 'voice-note-100.webm',
    },
  };
  assert.equal(isConversationVoiceMessage(dmVoice), true);

  const dmNonVoice = {
    id: 'dm-msg-2',
    from: 'user-1',
    to: 'user-2',
    text: 'Check this image',
    attachment: {
      id: 'att-2',
      mimetype: 'image/jpeg',
      filename: 'cat.jpg',
    },
  };
  assert.equal(isConversationVoiceMessage(dmNonVoice), false);

  const dmViewOnceVoice = {
    id: 'dm-msg-3',
    from: 'user-1',
    viewOnceMediaKind: 'audio',
  };
  assert.equal(isConversationVoiceMessage(dmViewOnceVoice), true);
});

test('isConversationVoiceMessage detects voice in group messages with root and nested mimetype', () => {
  // Root mimetype (as generated by encodeGroupFile)
  const groupVoiceRoot = {
    id: 'grp-msg-1',
    group: 'grp-1',
    text: JSON.stringify({
      __qc: 1,
      type: 'file',
      mimetype: 'audio/webm',
      filename: 'voice-note-200.webm',
      key: 'abc',
      nonce: '123',
    }),
  };
  assert.equal(isConversationVoiceMessage(groupVoiceRoot), true);

  // Explicit type === 'voice'
  const groupVoiceExplicit = {
    id: 'grp-msg-2',
    group: 'grp-1',
    text: JSON.stringify({
      __qc: 1,
      type: 'voice',
      key: 'abc',
      nonce: '123',
    }),
  };
  assert.equal(isConversationVoiceMessage(groupVoiceExplicit), true);

  // Nested payload mimetype
  const groupVoiceNested = {
    id: 'grp-msg-3',
    group: 'grp-1',
    text: JSON.stringify({
      __qc: 1,
      type: 'file',
      payload: {
        mimetype: 'audio/ogg',
        filename: 'recording.ogg',
      },
    }),
  };
  assert.equal(isConversationVoiceMessage(groupVoiceNested), true);

  // Non-voice group file
  const groupFileOther = {
    id: 'grp-msg-4',
    group: 'grp-1',
    text: JSON.stringify({
      __qc: 1,
      type: 'file',
      mimetype: 'application/pdf',
      filename: 'report.pdf',
    }),
  };
  assert.equal(isConversationVoiceMessage(groupFileOther), false);
});

test('preferConfirmedThreadText protects decrypted group payloads from being wiped by optimistic filename', () => {
  const optimisticFilename = 'voice-note-1700000000000.webm';
  const confirmedDecryptedPayload = JSON.stringify({
    __qc: 1,
    type: 'file',
    mimetype: 'audio/webm',
    filename: optimisticFilename,
    key: 'base64key',
    nonce: 'base64nonce',
    waveform: [20, 45, 80],
    durationSeconds: 3.5,
  });

  const chosenForMedia = preferConfirmedThreadText(optimisticFilename, confirmedDecryptedPayload, {
    mediaPending: true,
  });
  // Must preserve the confirmed structured payload so GroupMessageContent can decrypt and render the voice player!
  assert.equal(chosenForMedia, confirmedDecryptedPayload);

  // For regular DM text where confirmed body from server is empty (E2EE sealed text)
  const plainOptimistic = 'Hello friends!';
  const dmServerRaw = '';
  const chosenForDmText = preferConfirmedThreadText(plainOptimistic, dmServerRaw, {
    mediaPending: false,
  });
  assert.equal(chosenForDmText, plainOptimistic);
});

test('normalizeWaveform normalizes and resamples waveform peaks', () => {
  const peaks = [10, 50, 90, 120, -5, 30];
  const normalized = normalizeWaveform(peaks, 4);
  assert.equal(Array.isArray(normalized), true);
  assert.equal(normalized.length, 4);
  for (const n of normalized) {
    assert.ok(n >= 0 && n <= 100);
  }

  assert.equal(normalizeWaveform(null), null);
  assert.equal(normalizeWaveform([]), null);
});

test('voiceMetaFromMessage extracts waveform and durationSeconds from structured group messages', () => {
  const groupMsg = {
    text: JSON.stringify({
      __qc: 1,
      type: 'file',
      mimetype: 'audio/webm',
      waveform: [10, 20, 30, 40],
      durationSeconds: 12.4,
    }),
  };

  const meta = voiceMetaFromMessage(groupMsg);
  assert.equal(meta.durationSeconds, 12.4);
  assert.ok(Array.isArray(meta.waveform));
  assert.equal(meta.waveform.length, 4);
});
